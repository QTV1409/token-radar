// Launch Radar — the scoring model for token-radar-01.
//
// The board ranks every pre-token protocol in the sealed snapshot by an
// implied value: what its token might be worth if it launched one day and
// the market priced it like the tokens that already trade.
//
//   implied = tvl_usd x categoryMultiple x growthMultiplier x ageMultiplier
//
// categoryMultiple is NOT a hardcoded constant: it is the median
// market-cap / TVL ratio of the snapshot's own tokened protocols in the
// same category (at least 3 of them, else the global median over all
// tokened protocols with a market cap), clamped to [0.05, 1.50]. A DEX is
// priced like DEXes trade, a lender like lenders trade.
//
//   growthMultiplier = 1 + clamp(change_7d, -50, +150) / 100 x 0.40
//   ageMultiplier    = 0.85 + 0.15 x min(age_days, 1460) / 1460
//
// Growth is the protocol's TVL change over seven days from the snapshot
// (unknown: 0). Age is the days from listed_at to the snapshot's as_of
// date (unknown: 730 days, the middle of the range). Older pre-token
// protocols have run longer with real usage and no token, so they score
// a little higher; fast growers score higher; shrinkers score lower.
//
// No protocol name is ever special-cased. The same function scores every
// row, and the dashboard prints the four factors behind each rank so a
// reader can check the arithmetic.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, printed in the dashboard's "How the model works" panel. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  age_floor: number;
  age_range: number;
  age_days_cap: number;
  unknown_age_days: number;
  multiple_floor: number;
  multiple_cap: number;
  min_category_samples: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.4,
  growth_floor: -50,
  growth_cap: 150,
  age_floor: 0.85,
  age_range: 0.15,
  age_days_cap: 1460,
  unknown_age_days: 730,
  multiple_floor: 0.05,
  multiple_cap: 1.5,
  min_category_samples: 3,
};

export const MODEL_VERSION = 'radar-2-category-calibrated';

